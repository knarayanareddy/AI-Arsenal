#!/usr/bin/env node
// Report the editorial findings that the baseline is currently carrying.
//
// `validate:editorial:all` fails on findings that are not in
// docs/editorial-baseline.json, which is the right behaviour for a gate but a
// poor way to plan work: it prints a flat list in rule order. This script
// groups the same findings by file, ordered by how much work each file needs,
// and writes a page a maintainer can work down. It never edits content.
//
//   node scripts/audit-generated-prose.js            # human summary
//   node scripts/audit-generated-prose.js --out docs/generated-prose-audit.md

import fs from 'node:fs/promises';
import { validateEditorialQuality } from './validate-editorial-quality.js';

const args = process.argv.slice(2);
const outIndex = args.findIndex((a) => a === '--out' || a.startsWith('--out='));
let outPath = null;
if (outIndex >= 0) {
  const arg = args[outIndex];
  outPath = arg.includes('=') ? arg.split('=').slice(1).join('=') : args[outIndex + 1];
  if (!outPath) {
    console.error('--out requires a file path');
    process.exit(2);
  }
}

const BUCKETS = [
  {
    rule: 'hosted-claim-contradicted',
    title: 'False hosting claims',
    meaning: 'The entry says the subject has no self-hosted path while its own frontmatter documents a self-hostable or open-source artifact.',
    action: 'Replace with the real limitation. This is a wrong statement, not a style problem.'
  },
  {
    rule: 'rejected-boilerplate',
    title: 'Template prose',
    meaning: 'A sentence produced by filling a fixed frame with the entry\'s own description and alternative ids, so it states nothing about the subject.',
    action: 'Rewrite from the source material, or delete if the section already says it.'
  },
  {
    rule: 'repeated-paragraph',
    title: 'Paragraph shared across entries',
    meaning: 'The same prose appears in more than one entry, which is the signature of a bulk import.',
    action: 'Keep the paragraph in the entry it describes and rewrite the others.'
  }
];

const { issues } = await validateEditorialQuality({ mode: 'all' });
const byFile = new Map();
for (const issue of issues) {
  if (!byFile.has(issue.file)) byFile.set(issue.file, []);
  byFile.get(issue.file).push(issue.rule);
}
const byRule = new Map();
for (const issue of issues) byRule.set(issue.rule, (byRule.get(issue.rule) ?? 0) + 1);

const rows = [...byFile.entries()]
  .map(([file, rules]) => ({ file, count: rules.length, rules }))
  .sort((a, b) => b.count - a.count || a.file.localeCompare(b.file));

const lines = [];
lines.push('# Generated-prose audit');
lines.push('');
lines.push('Generated by `pnpm run audit:generated-prose` from the same rules the');
lines.push('editorial gate runs, so the counts here and the findings in');
lines.push('`docs/editorial-baseline.json` are the same set. It never edits content.');
lines.push('');
lines.push(`Entries with findings: **${rows.length}**. Findings: **${issues.length}**.`);
lines.push('');
lines.push('| Rule | Findings | What it means | Action |');
lines.push('|---|---:|---|---|');
for (const bucket of BUCKETS) {
  const count = byRule.get(bucket.rule) ?? 0;
  if (count === 0) continue;
  lines.push(`| \`${bucket.rule}\` | ${count} | ${bucket.meaning} | ${bucket.action} |`);
}
lines.push('');
lines.push('## Why these exist');
lines.push('');
lines.push('The 2026-06 and 2026-07 population batches were produced by generators');
lines.push('that filled a fixed sentence frame per section. The editorial gate at the');
lines.push('time rejected the frames it knew about, so these families passed: one');
lines.push('sentence about deployment-versus-cost comparison, one about a feature');
lines.push('list, one about maturity, and a limitation that asserts a hosted-only');
lines.push('product regardless of whether the tool is a local library. The retired');
lines.push('generator is in `quarantine/2026-10-24/`.');
lines.push('');
lines.push('The gate now names these frames, so changed files cannot reintroduce');
lines.push('them. What remains is the pre-existing text, listed below and carried by');
lines.push('the baseline until each entry is re-authored.');
lines.push('');
lines.push('## Worklist');
lines.push('');
lines.push('Ordered by finding count. A file with three findings usually needs one');
lines.push('section rewritten, not three edits.');
lines.push('');
lines.push('| Entry | Findings | Rules |');
lines.push('|---|---:|---|');
for (const row of rows) {
  const rules = [...new Set(row.rules)].sort().join(', ');
  lines.push(`| \`${row.file}\` | ${row.count} | ${rules} |`);
}
lines.push('');

const markdown = `${lines.join('\n')}`;
if (outPath) {
  await fs.mkdir(outPath.split('/').slice(0, -1).join('/') || '.', { recursive: true });
  await fs.writeFile(outPath, markdown);
  console.log(`Wrote ${outPath} (${rows.length} entries, ${issues.length} findings).`);
} else {
  console.log(`Generated-prose audit: ${rows.length} entries, ${issues.length} findings.`);
  for (const [rule, count] of [...byRule.entries()].sort((a, b) => b[1] - a[1])) {
    console.log(`  ${rule.padEnd(32)} ${count}`);
  }
  for (const row of rows.slice(0, 15)) console.log(`  ${String(row.count).padStart(2)}  ${row.file}`);
  if (rows.length > 15) console.log(`  ... ${rows.length - 15} more (use --out to write the full worklist)`);
}
