#!/usr/bin/env node
// Content-debt reporter.
//
// Quantifies and prioritizes the two large, human-review-bound debts in the
// catalog so they can be burned down deliberately instead of guessed at:
//
//   1. the finding-level editorial baseline (docs/editorial-baseline.json) —
//      pre-existing full-catalog editorial findings that are tolerated today; and
//   2. the enrichment_status distribution across content entries (how much of
//      the catalog is still `draft` vs `reviewed`/`verified`).
//
// This script only MEASURES and PRIORITIZES. It never rewrites content or flips
// verification status: reducing these debts requires bespoke, domain-aware
// editing and honest human review, which cannot be safely automated.
//
// Usage:
//   node scripts/report-content-debt.js            # human-readable summary
//   node scripts/report-content-debt.js --json      # machine-readable JSON
//   node scripts/report-content-debt.js --out FILE  # write a markdown roadmap
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import chalk from 'chalk';
import { getEntryFiles, readMarkdown, inferEntryType } from './utils/frontmatter.js';

// Top-level content vertical from a repo-relative path, e.g.
// "content/projects/agent-systems/x.md" -> "projects".
export function verticalOf(file) {
  const parts = String(file).split('/');
  return parts[0] === 'content' && parts[1] ? parts[1] : 'unknown';
}

// enrichment_status values in the wild often carry trailing prose
// ("draft; metadata verified via arXiv ..."). Reduce to the leading token.
export function normalizeStatus(value) {
  if (value == null) return 'unset';
  const token = String(value).trim().split(/[\s;`]/)[0].toLowerCase();
  return token || 'unset';
}

function sortedCounts(map) {
  return [...map.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
}

// Aggregate the editorial baseline entries by rule, by vertical, and by file.
export function aggregateBaseline(entries) {
  const byRule = new Map();
  const byVertical = new Map();
  const byFile = new Map();
  for (const entry of entries) {
    byRule.set(entry.rule, (byRule.get(entry.rule) ?? 0) + 1);
    const vertical = verticalOf(entry.file);
    byVertical.set(vertical, (byVertical.get(vertical) ?? 0) + 1);
    byFile.set(entry.file, (byFile.get(entry.file) ?? 0) + 1);
  }
  return {
    total: entries.length,
    byRule: sortedCounts(byRule),
    byVertical: sortedCounts(byVertical),
    topFiles: sortedCounts(byFile)
  };
}

// Aggregate enrichment status across records of { type, status }.
export function aggregateEnrichment(records) {
  const byStatus = new Map();
  const byType = new Map();
  for (const { type, status } of records) {
    const normalized = normalizeStatus(status);
    byStatus.set(normalized, (byStatus.get(normalized) ?? 0) + 1);
    const t = type ?? 'unknown';
    if (!byType.has(t)) byType.set(t, new Map());
    const inner = byType.get(t);
    inner.set(normalized, (inner.get(normalized) ?? 0) + 1);
  }
  const total = records.length;
  const draft = byStatus.get('draft') ?? 0;
  return {
    total,
    draftShare: total ? draft / total : 0,
    byStatus: sortedCounts(byStatus),
    byType: [...byType.entries()]
      .map(([type, inner]) => ({ type, total: [...inner.values()].reduce((a, b) => a + b, 0), byStatus: sortedCounts(inner) }))
      .sort((a, b) => b.total - a.total || a.type.localeCompare(b.type))
  };
}

function pct(part, whole) {
  return whole ? `${((part / whole) * 100).toFixed(1)}%` : '0%';
}

export function renderMarkdown(baseline, enrichment, topFileLimit = 25) {
  const lines = [];
  lines.push('# Content Debt Report');
  lines.push('');
  lines.push('> Generated by `pnpm run report:debt`. This report only measures and prioritizes debt; it does not modify content or verification status.');
  lines.push('');
  lines.push('## 1. Editorial baseline (suppressed full-catalog findings)');
  lines.push('');
  lines.push(`Total suppressed findings: **${baseline.total}** (see \`docs/editorial-baseline.json\`).`);
  lines.push('');
  lines.push('### By rule (attack the highest-count classes first)');
  lines.push('');
  lines.push('| Rule | Count |');
  lines.push('|---|---:|');
  for (const [rule, count] of baseline.byRule) lines.push(`| \`${rule}\` | ${count} |`);
  lines.push('');
  lines.push('### By content vertical');
  lines.push('');
  lines.push('| Vertical | Count |');
  lines.push('|---|---:|');
  for (const [vertical, count] of baseline.byVertical) lines.push(`| ${vertical} | ${count} |`);
  lines.push('');
  lines.push(`### Worst ${topFileLimit} files (most suppressed findings)`);
  lines.push('');
  lines.push('| File | Findings |');
  lines.push('|---|---:|');
  for (const [file, count] of baseline.topFiles.slice(0, topFileLimit)) lines.push(`| \`${file}\` | ${count} |`);
  lines.push('');
  lines.push('## 2. Enrichment status (verification debt)');
  lines.push('');
  lines.push(`Total content entries: **${enrichment.total}** — \`draft\` share: **${pct(Math.round(enrichment.draftShare * enrichment.total), enrichment.total)}**.`);
  lines.push('');
  lines.push('| Status | Count | Share |');
  lines.push('|---|---:|---:|');
  for (const [status, count] of enrichment.byStatus) lines.push(`| ${status} | ${count} | ${pct(count, enrichment.total)} |`);
  lines.push('');
  lines.push('### By type');
  lines.push('');
  lines.push('| Type | Total | Breakdown |');
  lines.push('|---|---:|---|');
  for (const row of enrichment.byType) {
    const breakdown = row.byStatus.map(([s, c]) => `${s}: ${c}`).join(', ');
    lines.push(`| ${row.type} | ${row.total} | ${breakdown} |`);
  }
  lines.push('');
  lines.push('## 3. Recommended burn-down order');
  lines.push('');
  lines.push('1. **Repeated paragraphs** — the largest, most mechanical class: locate the shared boilerplate paragraphs and replace each with entry-specific analysis (or remove the filler). Start with the worst files above.');
  lines.push('2. **Too-short / missing-technical-content sections** (projects & tools) — enrich `Overview`/`Architecture`/`Ecosystem Position` with named, entry-specific technical detail; these dominate the project/tool debt.');
  lines.push('3. **Verification debt** — move `draft` → `reviewed`/`verified` only after a real review. Do NOT bulk-flip the field; unverified-but-labeled-reviewed is worse than an honest `draft`.');
  lines.push('');
  lines.push('As findings are genuinely fixed, run `pnpm run editorial:baseline:prune` so the baseline shrinks (it is enforced shrink-only).');
  lines.push('');
  return lines.join('\n');
}

async function main() {
  const jsonMode = process.argv.includes('--json');
  const outIndex = process.argv.indexOf('--out');
  const outFile = outIndex !== -1 ? process.argv[outIndex + 1] : null;

  const baselineRaw = JSON.parse(await fs.readFile(path.join('docs', 'editorial-baseline.json'), 'utf8'));
  const baseline = aggregateBaseline(baselineRaw.entries ?? []);

  const records = [];
  for (const file of await getEntryFiles()) {
    const parsed = await readMarkdown(file);
    if (!parsed.hasFrontmatter) continue;
    records.push({ type: inferEntryType(file, parsed.data), status: parsed.data.enrichment_status });
  }
  const enrichment = aggregateEnrichment(records);

  if (jsonMode) {
    process.stdout.write(`${JSON.stringify({ baseline, enrichment }, null, 2)}\n`);
    return;
  }

  const markdown = renderMarkdown(baseline, enrichment);
  if (outFile) {
    await fs.mkdir(path.dirname(outFile), { recursive: true });
    await fs.writeFile(outFile, markdown);
    console.log(chalk.green(`Wrote content-debt report to ${outFile}`));
    return;
  }

  console.log(chalk.bold(`\nEditorial baseline: ${baseline.total} suppressed findings`));
  for (const [rule, count] of baseline.byRule) console.log(`  ${String(count).padStart(4)}  ${rule}`);
  console.log(chalk.bold(`\nWorst 10 files:`));
  for (const [file, count] of baseline.topFiles.slice(0, 10)) console.log(`  ${String(count).padStart(3)}  ${file}`);
  console.log(chalk.bold(`\nEnrichment status: ${enrichment.total} entries (draft ${pct(Math.round(enrichment.draftShare * enrichment.total), enrichment.total)})`));
  for (const [status, count] of enrichment.byStatus) console.log(`  ${String(count).padStart(4)}  ${status}`);
  console.log('');
}

const invokedDirectly = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  main().catch((error) => {
    console.error(chalk.red(error.message));
    process.exit(1);
  });
}
